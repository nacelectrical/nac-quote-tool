// Read the metrics out of the shipped Liberation Sans faces and write them as a
// module the PDF writer measures with.
//
// WHY BAKED RATHER THAN READ AT RUNTIME. `textWidth` is called thousands of
// times while a report lays out, from synchronous code, before the font bytes
// have necessarily been fetched. Parsing a 400 KB TrueType on every call — or
// making every caller async — to learn numbers that never change is the wrong
// trade. The numbers are extracted once, here, and checked in beside the fonts
// they came from.
//
//   node tools/extract-font-metrics.mjs
//
import { readFileSync, writeFileSync } from 'node:fs';

const FIRST = 32, LAST = 255;

/** The WinAnsi code page: byte -> Unicode. Only where it differs from Latin-1. */
const WINANSI_HIGH = {
  0x80: 0x20AC, 0x82: 0x201A, 0x83: 0x0192, 0x84: 0x201E, 0x85: 0x2026,
  0x86: 0x2020, 0x87: 0x2021, 0x88: 0x02C6, 0x89: 0x2030, 0x8A: 0x0160,
  0x8B: 0x2039, 0x8C: 0x0152, 0x8E: 0x017D, 0x91: 0x2018, 0x92: 0x2019,
  0x93: 0x201C, 0x94: 0x201D, 0x95: 0x2022, 0x96: 0x2013, 0x97: 0x2014,
  0x98: 0x02DC, 0x99: 0x2122, 0x9A: 0x0161, 0x9B: 0x203A, 0x9C: 0x0153,
  0x9E: 0x017E, 0x9F: 0x0178
};
const unicodeFor = (code) =>
  code >= 0x80 && code <= 0x9F ? (WINANSI_HIGH[code] ?? null) : code;

function readTtf(path) {
  const b = readFileSync(path);
  const u16 = (o) => b.readUInt16BE(o);
  const i16 = (o) => b.readInt16BE(o);
  const u32 = (o) => b.readUInt32BE(o);

  const numTables = u16(4);
  const tables = {};
  for (let i = 0; i < numTables; i++) {
    const p = 12 + i * 16;
    tables[b.toString('latin1', p, p + 4)] = { off: u32(p + 8), len: u32(p + 12) };
  }
  const need = ['head', 'hhea', 'hmtx', 'maxp', 'cmap', 'post', 'OS/2'];
  for (const t of need) if (!tables[t]) throw new Error(path + ' has no ' + t + ' table');

  const head = tables.head.off;
  const unitsPerEm = u16(head + 18);
  const bbox = [i16(head + 36), i16(head + 38), i16(head + 40), i16(head + 42)];
  const numHMetrics = u16(tables.hhea.off + 34);
  const numGlyphs = u16(tables.maxp.off + 4);

  // ── cmap: a (3,1) Unicode BMP subtable, format 4 ───────────────────────
  const cmap = tables.cmap.off;
  let sub = 0;
  for (let i = 0, n = u16(cmap + 2); i < n; i++) {
    const rec = cmap + 4 + i * 8;
    if (u16(rec) === 3 && u16(rec + 2) === 1) sub = cmap + u32(rec + 4);
  }
  if (!sub) throw new Error('no (3,1) cmap subtable');
  if (u16(sub) !== 4) throw new Error('cmap subtable is not format 4');
  const segX2 = u16(sub + 6), seg = segX2 / 2;
  const endO = sub + 14, startO = endO + segX2 + 2;
  const deltaO = startO + segX2, rangeO = deltaO + segX2;
  const glyphFor = (cp) => {
    for (let i = 0; i < seg; i++) {
      if (u16(endO + i * 2) < cp) continue;
      const start = u16(startO + i * 2);
      if (start > cp) return 0;
      const range = u16(rangeO + i * 2);
      if (range === 0) return (cp + i16(deltaO + i * 2)) & 0xFFFF;
      const gi = rangeO + i * 2 + range + (cp - start) * 2;
      const g = u16(gi);
      return g === 0 ? 0 : (g + i16(deltaO + i * 2)) & 0xFFFF;
    }
    return 0;
  };

  const advance = (gid) => {
    const i = Math.min(gid, numHMetrics - 1);
    return u16(tables.hmtx.off + i * 4);
  };
  const scale = (v) => Math.round(v * 1000 / unitsPerEm);

  const widths = [];
  const missing = [];
  for (let code = FIRST; code <= LAST; code++) {
    const cp = unicodeFor(code);
    const gid = cp === null ? 0 : glyphFor(cp);
    if (cp !== null && gid === 0 && code !== 0xAD) missing.push(code);
    widths.push(scale(advance(gid)));
  }

  const os2 = tables['OS/2'].off;
  return {
    unitsPerEm, numGlyphs,
    bbox: bbox.map(scale),
    ascent: scale(i16(os2 + 68)),          // sTypoAscender
    descent: scale(i16(os2 + 70)),         // sTypoDescender (negative)
    capHeight: tables['OS/2'].len > 88 ? scale(i16(os2 + 88)) : 700,
    italicAngle: i16(tables.post.off + 4), // fixed 16.16, integer part
    stemV: 80,
    widths, missing,
    bytes: b.length
  };
}

const faces = {
  regular: readTtf('designer/vendor/fonts/LiberationSans-Regular.ttf'),
  bold: readTtf('designer/vendor/fonts/LiberationSans-Bold.ttf')
};
for (const [name, f] of Object.entries(faces)) {
  console.log(name, f.bytes + ' bytes,', f.numGlyphs + ' glyphs, unitsPerEm ' + f.unitsPerEm +
    ', ascent ' + f.ascent + ', descent ' + f.descent + ', cap ' + f.capHeight +
    (f.missing.length ? ', MISSING codes ' + f.missing.join(',') : ', every WinAnsi code present'));
}

const body = `// GENERATED by tools/extract-font-metrics.mjs — do not edit by hand.
//
// The metrics of the two Liberation Sans faces shipped in designer/vendor/fonts.
// Liberation Sans is metric-compatible with Arial and Helvetica and is licensed
// under the SIL Open Font License 1.1 (see LICENSE-OFL-1.1.txt beside the
// fonts), so it can be embedded in a document NAC sends to a customer.
//
// Widths are in 1/1000 em, indexed from WinAnsi code ${FIRST}.

export const FONT_FIRST_CODE = ${FIRST};
export const FONT_LAST_CODE = ${LAST};

export const FONT_FILES = Object.freeze({
  regular: 'LiberationSans-Regular.ttf',
  bold: 'LiberationSans-Bold.ttf'
});

export const FONT_NAMES = Object.freeze({
  regular: 'LiberationSans',
  bold: 'LiberationSans-Bold'
});

export const FONT_METRICS = Object.freeze({
${Object.entries(faces).map(([k, f]) => `  ${k}: Object.freeze({
    unitsPerEm: ${f.unitsPerEm},
    bbox: Object.freeze([${f.bbox.join(', ')}]),
    ascent: ${f.ascent}, descent: ${f.descent}, capHeight: ${f.capHeight},
    italicAngle: ${f.italicAngle}, stemV: ${f.stemV},
    widths: Object.freeze([
${f.widths.reduce((rows, w, i) => {
  const r = Math.floor(i / 16);
  (rows[r] = rows[r] || []).push(String(w).padStart(4));
  return rows;
}, []).map(r => '      ' + r.join(', ')).join(',\n')}
    ])
  })`).join(',\n')}
});
`;
writeFileSync('designer/ui/pdf-fonts.mjs', body);
console.log('wrote designer/ui/pdf-fonts.mjs');
